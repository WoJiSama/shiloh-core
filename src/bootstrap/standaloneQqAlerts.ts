type DiagnosticDescriptionSource = Pick<AgentDiagnosticEvent, 'stage' | 'operation' | 'outcome' | 'code' | 'details' | 'httpStatus' | 'errorKind' | 'sourceTag'>

export function describeAgentDiagnostic(event: DiagnosticDescriptionSource) {
  const details = event.details
  const code = event.code === 'redacted' ? undefined : event.code
  const operation = operationNames.get(event.operation) ?? (event.operation.startsWith('onebot.') ? '调用 QQ 接口' :
    event.operation.startsWith('mcp.') ? '连接 MCP 工具服务' : stageNames[event.stage])
  const status = event.httpStatus
  const httpReason = status === undefined ? undefined : httpReasons.get(status) ??
    (status >= 500 ? '外部服务暂时不可用。' : undefined)
  const glmReason = event.operation === 'summary_provider_http' && status === 400 && code && glmBadRequestReasons.get(code)
  const cause = details?.cause === 'http_error' ? httpReason ?? failureReasons.get('http_error') : details?.cause && failureReasons.get(details.cause)
  const rule = details?.rule && (ruleNames.get(details.rule) ?? details.rule)
  const location = details?.step && (stepNames.get(details.step) ?? details.step)
  const blocking = details?.blockingStep && stepNames.get(details.blockingStep)
  const slowest = details?.slowestCompletedStep && (stepNames.get(details.slowestCompletedStep) ?? details.slowestCompletedStep)
  const journal = event.operation === 'operation_journal' || event.operation === 'traffic_counter'
  const journalReason = code === 'diagnostic_journal_timeout' && location
    ? `操作日志确认超过五秒，当时环节为${location}${blocking ? `，前一批正在${blocking}` : ''}。`
    : undefined
  const queueReason = code === 'redis_command_queue_timeout' && details?.dispatchTurnPending !== undefined
    ? details.dispatchTurnPending ? 'Redis 命令尚未发出，超时时 Node.js 发送调度探针仍在等待。'
      : 'Node.js 已运行发送调度探针，Redis 命令到超时时仍留在客户端队列。'
    : undefined
  const limitUnit = code === 'search_body_too_large' || details?.cause === 'bilibili_size_limit' || details?.cause === 'bilibili_length_mismatch' ? ' 字节' :
    code === 'sim_send_turn_limit' || code === 'sim_send_minute_limit' || code === 'sim_send_hour_limit' ? ' 条' :
    code === 'model_response_truncated' || details?.cause === 'model_response_truncated' || details?.rule === 'cognition_output_truncated' ? ' token' :
    code?.includes('timeout') || code === 'semantic_provider_budget_elapsed' || details?.cause === 'semantic_recall_budget_elapsed' || details?.cause?.startsWith('douyin_browser_') && details.cause.endsWith('timeout') ? ' ms' : ''
  const evidence = [!journalReason && location && `环节 ${location}`, details?.field &&
    (stepNames.get(details.field) ?? `字段 ${details.field}`), rule,
    details?.expectedType && details.actualType && `要求 ${diagnosticTypeNames[details.expectedType]}，收到 ${diagnosticTypeNames[details.actualType]}`,
    details?.limit !== undefined && `界限 ${details.limit}${limitUnit}`, details?.nativeCode !== undefined && `平台返回码 ${details.nativeCode}`,
    details?.dispatched === undefined ? undefined : details.dispatched ? '已发起请求' : '未发起请求',
    details?.dispatchTurnMs !== undefined && `调度探针 ${details.dispatchTurnMs} ms`,
    details?.loopActiveMs !== undefined && `事件循环活跃 ${details.loopActiveMs} ms`,
    details?.configReadMs !== undefined && details.configReadCount !== undefined &&
      `同步配置读取 ${details.configReadCount} 次，共 ${details.configReadMs} ms`,
    details?.timeoutOverrunMs !== undefined && `超时回调延后 ${details.timeoutOverrunMs} ms`,
    details?.outputTokens !== undefined && `输出 ${details.outputTokens} token`,
    details?.reasoningTokens !== undefined && `推理占用 ${details.reasoningTokens} token`,
    details?.requestedSeq !== undefined && `提交的已读序号 ${details.requestedSeq}`,
    details?.firstUnseenSeq !== undefined && `最早未展示序号 ${details.firstUnseenSeq}`,
    details?.queueMs !== undefined && `排队 ${details.queueMs} ms`,
    details?.stepMs !== undefined && details.step !== 'journal_queue' && `当前环节 ${details.stepMs} ms`,
    slowest && details?.slowestCompletedStepMs !== undefined && `前面最慢的环节 ${slowest} ${details.slowestCompletedStepMs} ms`,
    details?.bytesWritten !== undefined && details.bytesExpected !== undefined &&
      `已写入发送缓冲区 ${details.bytesWritten}/${details.bytesExpected} 字节`,
    details?.causeEventId && `关联记录 ${details.causeEventId}`,
    event.sourceTag && `来源 ${event.sourceTag}`, details?.cause && details.cause !== code && `关联原因 ${cause ?? details.cause}`].filter(Boolean).join(' · ')
  const result = details?.result && resultNames[details.result]
  const retrySeconds = details?.retryInMs === undefined ? undefined : (details.retryInMs / 1000).toLocaleString('zh-CN', { maximumFractionDigits: 2 })
  const disposition = [result, retrySeconds === undefined ? undefined : event.operation === 'simulation_wake_gate'
    ? `${retrySeconds} 秒后允许后续唤醒再请求预判` : `${retrySeconds} 秒后`,
    details?.attempt !== undefined && `第 ${details.attempt}${details.maxAttempts === undefined ? '' : `/${details.maxAttempts}`} 次`].filter(Boolean).join(' · ')
  if (event.outcome === 'succeeded' || event.outcome === 'started') return { operation, evidence, result: disposition }
  const knownReason = code && !genericCodes.has(code) && failureReasons.get(code)
  const reason = journalReason || queueReason || glmReason || (rule ? `${details?.field ? `${details.field} ` : ''}${rule}。` : undefined) ||
    (code === 'http_error' ? httpReason : undefined) || (details?.result === 'fallback_used' ? knownReason : undefined) ||
    (cause === failureReasons.get('diagnostic_metadata_redacted') ? undefined : cause) ||
    (knownReason && code !== 'http_error' ? knownReason : undefined) || httpReason || exceptionReasons.get(event.errorKind) || knownReason ||
    (event.outcome === 'unknown' ? '暂时无法确认操作是否完成。' : code && warningCodes.has(code)
      ? '这条兼容日志缺少可确认的原因。' : '此操作未提供可确认的失败原因。')
  return { operation, reason, evidence, result: disposition }
}

export function resolveStandaloneQqAlertOwner(connectionId: string, connections: readonly PlatformConnection[], masters: readonly PlatformUserRef[]): PlatformUserRef {
  const connection = connections.find(candidate => candidate.id === connectionId)
  const owner = masters[0]
  if (!connection || connection.account.platform !== 'qq' || connection.account.namespace !== 'global' || masters.length !== 1 ||
      owner?.platform !== 'qq' || owner.namespace !== 'global' || qqId(owner.id) !== owner.id ||
      connections.some(candidate => candidate.account.platform === 'qq' && candidate.account.namespace === 'global' && candidate.account.id === owner.id)) {
    throw new Error('QQ 主人告警需要一个有效 QQ 连接和唯一的 bilibiliQuality.masters 主人')
  }
  return owner
}

export function formatQqOwnerAlerts(batch: AlertBatch): string {
  const time = new Intl.DateTimeFormat('zh-CN', { timeZone: 'Asia/Shanghai', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', second: '2-digit', hourCycle: 'h23' })
  function format(includeOperation: boolean, includeContext: boolean, rowLimit = Infinity) {
    const lines = batch.alerts.map(alert => {
      const warning = alert.code !== undefined && warningCodes.has(alert.code)
      const outcome = alert.details?.result === 'fallback_used' ? '已降级' : alert.outcome === 'unknown' ? '结果待确认' : warning ? '出现警告' : '失败'
      const description = describeAgentDiagnostic(alert)
      const code = alert.code === 'redacted' ? undefined : alert.code
      const status = alert.httpStatus
      const details = [code && `错误码 ${code}`, status !== undefined && `HTTP 状态 ${status}`,
        includeOperation && alert.operation !== 'redacted' && `操作标识 ${alert.operation}`].filter(Boolean).join(' · ')
      const timing = includeContext && alert.lastAt > 0 && alert.lastAt <= 8_640_000_000_000_000 ?
        `${time.format(alert.lastAt)}${alert.durationMs === undefined ? '' : ` · 耗时 ${alert.durationMs} ms`}` : ''
      const heading = `${description.operation}${outcome}，共 ${alert.count} 次`
      const trace = alert.traceId && `追踪编号 ${alert.traceId}`
      const firstTrace = includeContext && alert.firstTraceId && `本批首条追踪编号 ${alert.firstTraceId}`
      const receipt = alert.deliveryState && `平台回执 ${deliveryNames[alert.deliveryState]}`
      const reasonLimit = Math.max(0, rowLimit - heading.length - details.length - (trace?.length ?? 0) - 3)
      const reason = description.reason && (description.reason.length <= reasonLimit ? description.reason :
        reasonLimit ? description.reason.slice(0, reasonLimit - 1) + '…' : '')
      return [heading, reason, details, trace, firstTrace, receipt, includeContext && description.evidence, includeContext && description.result, timing].filter(Boolean).join('\n')
    })
    return ['【助手运行告警】', ...lines].join('\n\n')
  }
  const text = format(true, true)
  if (text.length <= QQ_OWNER_ALERT_MAX_LENGTH) return text
  const compact = format(false, true)
  if (compact.length <= QQ_OWNER_ALERT_MAX_LENGTH) return compact
  const basic = format(false, false)
  if (basic.length <= QQ_OWNER_ALERT_MAX_LENGTH) return basic
  return format(false, false, Math.floor((QQ_OWNER_ALERT_MAX_LENGTH - '【助手运行告警】'.length) / batch.alerts.length) - 2)
}
